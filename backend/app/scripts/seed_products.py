def seed_database():
    with SessionLocal() as db:
        print(f"Seeding {len(SEED_PRODUCTS)} curated products into database...")
        for i, item in enumerate(sorted(SEED_PRODUCTS, key=lambda x: x["corrected_score"], reverse=True), 1):
            p = db.get(Product, item["asin"])
            if p is None:
                p = Product(asin=item["asin"])
                db.add(p)
            p.title = item["title"]
            p.product_category = item["product_category"]
            p.price_inr = item["price_inr"]
            p.corrected_score = item["corrected_score"]
            p.star_average = item["star_average"]
            p.uncertainty = item["uncertainty"]
            p.review_count = item["review_count"]
            p.aspect_summary = item["aspect_summary"]
            p.rank_position = i
            p.eb_shrinkage_factor = 0.88
            p.trust_weighted_score = round(item["corrected_score"] * 0.98, 2)

        db.commit()
        print(f"✅ Successfully seeded {len(SEED_PRODUCTS)} products with Indian pricing and VERA scores!")


